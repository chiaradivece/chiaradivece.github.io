#!/usr/bin/env python3
"""Build _includes/icon-sprite.html from the SVGs in _includes/icons/.

Every icon is defined once as a <symbol>; _includes/icon.html then references it
with <use>, so the page ships each icon once instead of once per use.
Run this after adding or removing an icon:

    python3 bin/build_icon_sprite.py
"""
import os
import re

ROOT = os.path.join(os.path.dirname(__file__), "..", "_includes")
ICONS = os.path.join(ROOT, "icons")

symbols = []
for name in sorted(os.listdir(ICONS)):
    if not name.endswith(".svg"):
        continue
    svg = open(os.path.join(ICONS, name), encoding="utf-8").read()
    viewbox = re.search(r'viewBox="([^"]+)"', svg).group(1)
    inner = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", svg.strip(), flags=re.S)
    inner = re.sub(r"<title>.*?</title>", "", inner)
    symbols.append(f'  <symbol id="i-{name[:-4]}" viewBox="{viewbox}">{inner}</symbol>')

with open(os.path.join(ROOT, "icon-sprite.html"), "w", encoding="utf-8") as f:
    f.write("<!-- Generated by bin/build_icon_sprite.py. Do not edit by hand. -->\n")
    f.write('<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">\n')
    f.write("\n".join(symbols) + "\n</svg>\n")
print(f"{len(symbols)} icons")
